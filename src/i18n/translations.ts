// Widen literal string types to `string` so both fr/en dictionaries satisfy
// the same shape (otherwise TS infers narrow literals from the fr object).
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
  ? readonly Widen<U>[]
  : T extends object
  ? { [K in keyof T]: Widen<T[K]> }
  : T;

export type TranslationShape = Widen<typeof translations.fr>;
